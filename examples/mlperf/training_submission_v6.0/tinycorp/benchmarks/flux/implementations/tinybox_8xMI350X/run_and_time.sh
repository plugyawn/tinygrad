#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

export SUBMISSION_PLATFORM="tinybox_8xMI350X"
export LOGMLPERF=1
export MODEL="flux"
export SEED="${SEED:-$RANDOM}"
export RUN_NAME="${RUN_NAME:-$(date "+%m%d%H%M%S")_${SEED}}"

LOGFILE="${LOGFILE:-flux_8xMI350x_${RUN_NAME}.log}"

env -u RUNMLPERF PRETRAINED="" FAKEDATA=1 BENCHMARK=1 INITMLPERF=1 CKPT=0 EVAL_INTERVAL=1 TRAIN_STEPS=1 EVAL_STEPS=1 \
  FLUX_HIDDEN_SIZE=128 FLUX_ATTENTION_HEADS=1 FLUX_DOUBLE_STREAM_BLOCKS=0 FLUX_SINGLE_STREAM_BLOCKS=0 FLUX_MLP_RATIO=1.0 FLUX_T5_TOKENS=8 \
  "${SCRIPT_DIR}/dev_run.sh" | tee "${LOGFILE}"

env -u INITMLPERF -u FAKEDATA -u BENCHMARK -u CKPT -u EVAL_INTERVAL -u TRAIN_STEPS -u EVAL_STEPS \
  -u FLUX_HIDDEN_SIZE -u FLUX_ATTENTION_HEADS -u FLUX_DOUBLE_STREAM_BLOCKS -u FLUX_SINGLE_STREAM_BLOCKS \
  -u FLUX_MLP_RATIO -u FLUX_T5_TOKENS RUNMLPERF=1 GPUS=8 BS=128 EVAL_BS=128 LR=1e-4 WARMUP_STEPS=1000 MAX_NORM=1.0 \
  CKPT=1 EVAL_INTERVAL=0 STOP_IF_CONVERGED=1 TOTAL_CKPTS=7 DEFAULT_FLOAT=bfloat16 "${SCRIPT_DIR}/dev_run.sh" | tee -a "${LOGFILE}"
